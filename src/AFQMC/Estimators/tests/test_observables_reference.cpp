// Regression tests for full2rdm, diagonal2rdm, and spinspinobs: compare the new
// (nda/mpi_context_t based) implementations against reference data produced by
// the old (pre-refactor) implementations on identical inputs. The reference
// file is generated by src/AFQMC/Estimators/tests/dump_rdm_reference.cpp in
// ~/src/SAFIRE_old, which writes three top-level case subgroups (closed,
// collinear, noncollinear) each with its own Metadata, Inputs, DiagTwoRDM, and
// SpinSpin. full2rdm output lives only under /collinear (full2rdm aborts on the
// other walker types).

